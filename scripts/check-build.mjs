import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const html = await readFile('dist/index.html', 'utf8');
const content = JSON.parse(await readFile('src/content/site.json', 'utf8'));
assert.equal((html.match(/<h1\b/g) || []).length, 1, 'Exactly one page heading');
for (const item of content.services.items) assert.ok(html.includes(item.description), `Prerendered service: ${item.title}`);
for (const id of ['main', 'services', 'philosophy', 'contact']) assert.ok(html.includes(`id="${id}"`), `Navigation target ${id}`);
assert.ok(html.includes('name="description"'));
assert.ok(html.includes('property="og:title"'));
assert.ok(html.includes('name="twitter:card" content="summary_large_image"'));
const socialImage = await readFile(`dist${content.seo.socialImage.path}`);
assert.equal(socialImage.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', 'Share asset is a PNG');
assert.equal(socialImage.readUInt32BE(16), content.seo.socialImage.width, 'Share image width matches metadata');
assert.equal(socialImage.readUInt32BE(20), content.seo.socialImage.height, 'Share image height matches metadata');
assert.ok(socialImage.length < 1024 * 1024, 'Share image stays below 1 MB');
const imageTag = html.match(/property="og:image" content="([^"]+)"/);
assert.ok(imageTag, 'Absolute share image URL is present');
const imageUrl = new URL(imageTag[1]);
assert.equal(imageUrl.pathname, content.seo.socialImage.path);
assert.match(imageUrl.searchParams.get('v'), /^[a-f0-9]{12}$/, 'Content version refreshes changed images');
assert.ok(html.includes(`name="twitter:image" content="${imageTag[1]}"`));
assert.ok(html.includes('property="og:image:alt"'));
assert.ok(html.includes('property="og:image:type" content="image/png"'));
assert.ok(!html.includes('<!--app-html-->') && !html.includes('<!--seo-head-->'));
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1]);
assert.equal(schema.name, content.brand.name);
assert.equal(schema.hasOfferCatalog.itemListElement.length, content.services.items.length);
assert.ok((await readFile('dist/robots.txt', 'utf8')).includes('User-agent: *'));
console.log('Build checks passed: prerendered content, navigation, metadata and structured data.');
